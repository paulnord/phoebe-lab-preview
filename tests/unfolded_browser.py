"""Check the original timestamps, live folding, session ephemeris and chart visibility."""
import json
import sys
from pathlib import Path
import numpy as np
from playwright.sync_api import sync_playwright, expect

with sync_playwright() as pw:
    browser = pw.chromium.launch()
    page = browser.new_page()
    page.goto(sys.argv[1])
    export = page.locator('#export-button')
    expect(export).to_be_enabled(timeout=150000)
    panel = page.locator('#time-panel')
    expect(panel).to_be_hidden()
    choice = page.locator('#example-choice')
    choice.select_option('examples/kepler-4544587-time.json')
    page.locator('#example-button').click()
    expect(panel).to_be_visible()
    expect(page.locator('#dataset-description')).to_contain_text('1297')
    expect(page.locator('#time-origin')).to_contain_text('BJD')
    expect(page.locator('#number-period')).to_have_value('2.1890973')
    expect(export).to_be_enabled(timeout=150000)
    data = json.loads((Path(__file__).resolve().parents[1] / 'site/examples/kepler-4544587-time.json').read_text())
    times = np.array(data['x'])
    chart = "document.querySelector('#light-curve').chart.data.phase"
    def expected(period, epoch=None):
        return np.sort(((times - (data['epoch'] if epoch is None else epoch)) / period + .5) % 1 - .5)
    np.testing.assert_allclose(page.evaluate(chart), expected(data['period']), atol=2e-13, rtol=0)
    slider = page.locator('#range-period')
    span = page.locator('#period-span')
    expect(span).to_have_value('0.001')
    slider.focus()
    slider.press('ArrowRight')
    expect(page.locator('#number-period')).to_have_value('2.1890974')
    np.testing.assert_allclose(page.evaluate(chart), expected(2.1890974), atol=2e-13, rtol=0)
    span.select_option('0.00001')
    expect(slider).to_have_value('0')
    slider.press('ArrowLeft')
    expect(page.locator('#number-period')).to_have_value('2.1890973')
    span.select_option('full')
    slider.dispatch_event('pointerdown')
    slider.evaluate("s=>{s.value='2.25';s.dispatchEvent(new Event('input'))}")
    np.testing.assert_allclose(page.evaluate(chart), expected(2.25), atol=2e-13, rtol=0)
    expect(export).to_be_disabled()
    expect(page.locator('#rms-stat')).to_have_text('—')
    expect(page.locator('#residual-summary')).to_contain_text('Preview')
    residual_chart = "document.querySelector('#residual-curve').chart.data"
    preview = page.evaluate(residual_chart)
    assert len(preview['residual']) == len(times) and np.isfinite(preview['residual']).all()
    slider.dispatch_event('pointerup')
    expect(page.locator('#residual-summary')).to_contain_text('-point PHOEBE curve', timeout=120000)
    expect(page.locator('#rms-stat')).to_have_text('—')
    expect(export).to_be_enabled(timeout=150000)
    np.testing.assert_allclose(page.evaluate(chart), expected(2.25), atol=2e-13, rtol=0)
    epoch = page.locator('#range-epoch')
    page.locator('#epoch-span').select_option('0.00001')
    with page.expect_download() as old_curve:
        export.click()
    phases, model = np.loadtxt(old_curve.value.path(), delimiter=',', skiprows=1).T
    epoch.dispatch_event('pointerdown')
    epoch.evaluate("s=>{s.value='50';s.dispatchEvent(new Event('input'))}")
    shifted = round(data['epoch']+0.000005, 7)
    expect(page.locator('#number-epoch')).to_have_value(f'{shifted:.7f}')
    expect(export).to_be_disabled()
    expect(page.locator('#residual-summary')).to_contain_text('Live · exact')
    expect(page.locator('#chi-stat')).to_have_text('—')
    live = page.evaluate(residual_chart)
    observed, sigma = np.asarray(live['flux']), np.asarray(live['sigma'])
    predicted = np.interp(live['phase'], phases, model)
    scale = np.sum(observed*predicted/sigma**2) / np.sum(predicted**2/sigma**2)
    np.testing.assert_allclose(live['residual'], observed-scale*predicted, atol=1e-12, rtol=0)
    epoch.dispatch_event('pointerup')
    expect(export).to_be_enabled(timeout=15000)
    np.testing.assert_allclose(live['residual'], page.evaluate(residual_chart)['residual'], atol=1e-12, rtol=0)
    expect(page.locator('#model-status')).to_contain_text('updated observation comparison')
    np.testing.assert_allclose(page.evaluate(chart), expected(2.25, shifted), atol=2e-13, rtol=0)
    with page.expect_download() as saved:
        page.locator('#save-button').click()
    session = saved.value.path().read_bytes()
    assert json.loads(session)['dataset']['x'] == data['x']
    choice.select_option('example.json')
    page.locator('#example-button').click()
    expect(panel).to_be_hidden()
    page.locator('#import-button').click()
    page.locator('#data-file').set_input_files(dict(name='time-session.json',mimeType='application/json',buffer=session))
    expect(panel).to_be_visible()
    expect(page.locator('#number-period')).to_have_value('2.2500000')
    expect(export).to_be_enabled(timeout=150000)
    np.testing.assert_allclose(page.evaluate(chart), expected(2.25, shifted), atol=2e-13, rtol=0)
    number = page.locator('#number-period')
    span.select_option('0.00001')
    for value, key in [('100','ArrowRight'),('0.1','ArrowLeft')]:
        number.fill(value)
        number.press('Tab')
        expect(slider).to_have_value('0')
        slider.press(key)
        assert float(number.input_value()) == float(value)
    ecc = page.locator('#range-eccentricity')
    page.locator('#eccentricity-span').select_option('0.01')
    ecc.press('ArrowRight')
    expect(page.locator('#number-eccentricity')).to_have_value('0.2751')
    page.locator('#number-eccentricity').fill('0')
    page.locator('#number-eccentricity').press('Tab')
    ecc.press('ArrowLeft')
    expect(page.locator('#number-eccentricity')).to_have_value('0.0000')
    print('Verified fine controls, live approximate and partial residuals, exact epoch residuals and session ephemeris.')
    browser.close()
